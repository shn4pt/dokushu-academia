//
// 書き方の約束(docs/pilot/course-audience.md):
//  - 現行のレッスンが扱っている範囲に限る。持ち帰れることには、実在のレッスン ID を付ける(テストで、その講座のレッスンか確かめる)。
//  - 講座ごとの固有の用途を書く。全講座に「AI」「一人起業」の定型文を入れない。AI との関係が間接的なら、そう書く。
//  - 「全てを一人でこなせる」「専門家が不要になる」「AI に任せれば成功する」とは書かない。
//  - 読者設定は作者の方針で、需要や学習効果が確かめられたものではない。

