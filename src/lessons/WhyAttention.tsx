function Body() {
  return (
    <>
      <h3>文脈を扱うという課題</h3>
      <p>
        次のトークンを正しく予測するには、離れた位置にある情報が必要なことがあります。たとえば
        「鍵を机の上に置いたまま出かけたので、<strong>それ</strong>を取りに戻った」の「それ」が何を指すかは、
        文の前半を見ないと決まりません。
      </p>

      <h3>RNNの限界</h3>
      <p>
        Transformer以前の主流だった<strong>RNN</strong>は、トークンを1つずつ順に読み、過去の情報を
        1本の固定長ベクトル(隠れ状態)に詰め込んで引き継ぎました。
      </p>
      <pre>{`x1 → [h1] → x2 → [h2] → x3 → [h3] → ... → [hT]
        ↑ 過去のすべてがこの1本のベクトルに圧縮される`}</pre>
      <ul>
        <li><strong>情報の欠落</strong>:遠い過去の情報ほど、何度も上書きされて薄れる。</li>
        <li><strong>勾配の消失</strong>:学習時、離れた位置同士の関係に誤差がうまく伝わらない。</li>
        <li><strong>並列化できない</strong>:前の時刻の計算が終わらないと次に進めず、GPUの並列性を活かしにくい。</li>
      </ul>

      <h3>Attentionの発想</h3>
      <p>
        過去を1本に圧縮するのをやめて、<strong>必要なときに過去の任意の位置を直接参照する</strong>、という発想です。
        各トークンが「どの位置をどれだけ見るか」を重みで決めます。
      </p>
      <pre>{`食べた ──(強く参照)──→ 猫
       ──(強く参照)──→ 魚
       ──(弱く参照)──→ が, を`}</pre>
      <ul>
        <li>どれだけ離れていても、位置間の距離は1ステップ(直接つながる)。</li>
        <li>全トークンの計算を同時に行えるため、GPUで効率よく並列化できる。</li>
        <li>代償として、計算量とメモリが系列長の2乗で増える。</li>
      </ul>

      <h3>Transformerへ</h3>
      <p>
        「Attention Is All You Need」(2017)は、RNNを使わずattentionと小さなネットワークだけで系列を処理する構造として
        Transformerを提案しました。次のレッスンでattentionの計算を具体的に見ていきます。
      </p>
    </>
  )
}

